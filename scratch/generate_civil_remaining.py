# ─────── Question Generation Engine ───────

def generate_questions_for_item(item_key, item_data):
    configs = get_question_configs()
    questions = []
    
    facts = item_data["facts"]
    # Ensure we have at least 5 facts. If we have 5-10 facts, we can cycle through them.
    # We will build a pool of combinations or generate by selecting facts in a balanced way.
    
    # Track usage counts to keep them balanced
    fact_usage = [0] * len(facts)
    
    for q_idx in range(60):
        cfg = configs[q_idx]
        diff = cfg["difficulty"]
        polarity = cfg["polarity"]
        correct_ans = cfg["answer"] # 1 to 5
        
        # 1. Select 5 facts for this question.
        # We want to select 5 unique facts, prioritizing the ones with lower usage count.
        available_indices = list(range(len(facts)))
        # Sort indices by usage count first, then random shuffle to make it varied
        random.shuffle(available_indices)
        available_indices.sort(key=lambda idx: fact_usage[idx])
        
        selected_indices = available_indices[:5]
        # increment usage
        for idx in selected_indices:
            fact_usage[idx] += 1
            
        selected_facts = [facts[idx] for idx in selected_indices]
        
        # 2. Build options based on polarity
        # correct_ans is 1-indexed (1 to 5).
        options = [""] * 5
        why_explanations = []
        option_meta = []
        
        # Determine target fact index (correct_ans - 1)
        target_fact_idx = correct_ans - 1
        
        # Build options
        for opt_idx in range(5):
            fact = selected_facts[opt_idx]
            is_target = (opt_idx == target_fact_idx)
            
            if polarity == "Incorrect":
                # Question asks: "옳지 않은 것은?"
                # Target option should be FALSE_STMT (which makes this option the correct answer)
                # Distractor options should be TRUE_STMT (which are correct statements, so they are wrong answers)
                if is_target:
                    text = fact["f"]
                    is_correct_option = True
                    why = f"틀린 설명입니다. {fact['exp']}"
                else:
                    text = fact["t"]
                    is_correct_option = False
                    why = f"옳은 설명입니다. 민법 {fact['art']}에 근거합니다."
            else:
                # Question asks: "옳은 것은?"
                # Target option should be TRUE_STMT (which makes this option the correct answer)
                # Distractor options should be FALSE_STMT (which are incorrect statements, so they are wrong answers)
                if is_target:
                    text = fact["t"]
                    is_correct_option = True
                    why = f"옳은 설명입니다. 민법 {fact['art']}에 근거합니다. {fact['exp']}"
                else:
                    text = fact["f"]
                    is_correct_option = False
                    why = f"틀린 설명입니다. {fact['exp']}"
            
            # format option text
            prefix_char = ["①", "②", "③", "④", "⑤"][opt_idx]
            options[opt_idx] = f"{prefix_char} {text}"
            
            # option meta structure
            option_meta.append({
                "correct": is_correct_option,
                "why": why,
                "articles": [fact["art"]],
                "principle": item_data["item"] + " 핵심 법리",
                "case": { "holding": fact["exp"] if "대판" in fact["art"] else "", "no": None }
            })
            why_explanations.append(f"{prefix_char} {why}")
            
        # 3. Formulate question text
        subj = item_data["sub_subject"]
        ch = item_data["chapter"]
        sec = item_data["section"]
        it = item_data["item"]
        
        q_text = f"{it}에 관한 설명 중 "
        if polarity == "Incorrect":
            q_text += "옳지 않은 것은?"
        else:
            q_text += "옳은 것은?"
            
        # For L5 questions, add a case study header to make it complex
        if diff == 5:
            scenario_headers = [
                f"[사례형] A는 B의 부동산에 대하여 {it}에 따른 법률관계를 맺었다. 이에 관한 설명 중 ",
                f"[사례형] 공동소유 또는 담보권 설정 과정에서 {it}에 관한 법적 다툼이 발생하였다. 다음 설명 중 ",
                f"[사례형] 채무자 A와 물상보증인 B, 채권자 C 간의 {it}에 관한 복잡한 법률관계 중 "
            ]
            q_text = random.choice(scenario_headers) + ("옳지 않은 것은?" if polarity == "Incorrect" else "옳은 것은?")
            
        # 4. Formulate explanation text
        target_fact = selected_facts[target_fact_idx]
        explanation = f"【정답 해설】\n정답은 {correct_ans}번입니다.\n{target_fact['art']}에 따르면, {target_fact['exp']}\n\n【선지별 해설】\n" + "\n".join(why_explanations)
        
        # 5. Question ID
        slug = item_key.replace("_", "-")
        qid = f"practice-civil-{slug}-d{diff}-{q_idx+1:03d}"
        
        q = {
            "id": qid,
            "difficulty": diff,
            "question_type": "판례형" if any("대판" in f["art"] for f in selected_facts) else "조문형",
            "question": q_text,
            "options": options,
            "answer": str(correct_ans),
            "explanation": explanation,
            "option_meta": option_meta
        }
        questions.append(q)
        
    return questions

