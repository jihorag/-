    old_ans_str = q["answer"]
    old_ans = int(old_ans_str) - 1 # 0-based index
    
    new_ans = idx // 12
    new_ans_str = str(new_ans + 1)
    
    if old_ans != new_ans:
        # Swap options
        options = q["options"]
        temp = options[old_ans]
        options[old_ans] = options[new_ans]
        options[new_ans] = temp
        q["answer"] = new_ans_str

