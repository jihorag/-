def main():
    print("=== Processing All Remaining Real Estate Practice Files ===")
    
    with open(TAX_INDEX, "r", encoding="utf-8") as f:
        data = json.load(f)
    
    leaves = data.get("leaves", [])
    print(f"Loaded {len(leaves)} total leaves from ai_taxonomy_index.json")
    
    updated_count = 0
    skipped_count = 0
    
    for leaf in leaves:
        leaf_id = leaf["id"]
        if leaf_id in SKIPPED_LEAVES:
            print(f"Skipping already revamped high-difficulty file: {leaf_id}")
            skipped_count += 1
            continue
            
        path = leaf["path"]
        chapter = path[0]
        section = path[1]
        item = path[2] if len(path) > 2 else section
        
        # Determine Part number (e.g. PART03 -> Part 3)
        unit_code = leaf.get("unit_code", "PART03")
        part_num = int(re.search(r'\d+', unit_code).group())
        
        questions = []
        # Generate 50 questions
        for idx in range(1, 51):
            q_id = f"practice-realestate-{leaf_id.replace('realestate__', '')}-{idx:03d}"
            
            # Dispatch to appropriate generator
            if part_num == 3:
                q = generate_part3(item, idx)
            elif part_num == 4:
                q = generate_part4(item, idx)
            elif part_num == 5:
                q = generate_part5(item, idx)
            elif part_num == 6:
                q = generate_part6(item, idx)
            elif part_num == 7:
                q = generate_part7(item, idx)
            elif part_num == 8:
                q = generate_part8(item, idx)
            else: # part_num == 9 or default
                q = generate_part9(item, idx)
                
            q["id"] = q_id
            questions.append(q)
            
        out_data = {
            "meta": {
                "subject": "부동산학원론",
                "chapter": chapter,
                "section": section,
                "item": item,
                "source": "practice-set",
                "version": "v1",
                "created": "2026-06-07",
                "count": len(questions)
            },
            "questions": questions
        }
        
        out_path = os.path.join(PRACTICE_DIR, f"{leaf_id}.json")
        with open(out_path, "w", encoding="utf-8") as f_out:
            json.dump(out_data, f_out, ensure_ascii=False, indent=2)
            
        updated_count += 1
        
    print(f"Successfully finished. Updated: {updated_count} files, Skipped: {skipped_count} files.")

if __name__ == "__main__":
    main()
