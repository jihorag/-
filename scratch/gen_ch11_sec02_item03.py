for idx, q in enumerate(questions_list):
    ans = int(q["answer"])
    choice_counts[ans] += 1
    
    is_correct = "옳은 것" in q["question"]
    if is_correct:
        correct_count += 1
    else:
        incorrect_count += 1
        
    diff = q["difficulty"]
    difficulty_counts[diff] += 1

print(f"Total questions: {len(questions_list)}")
print(f"Choice distribution: {choice_counts}")
print(f"Polarity - Incorrect (옳지 않은 것): {incorrect_count}, Correct (옳은 것): {correct_count}")
print(f"Difficulty counts: {difficulty_counts}")

