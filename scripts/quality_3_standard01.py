def get_next_id(data, ch):
    next_id = max(
        (int(m.group(1)) for q in data['questions']
         for m in [re.match(rf'practice-{ch}-(\d+)', q['id'])] if m),
        default=0
    ) + 1
    return next_id


def main():
    ch = '3'
    path = DATA_DIR / f'{ch}.json'
    data = json.loads(path.read_text(encoding='utf-8'))
    next_id = get_next_id(data, ch)

    added = []
    for i, p in enumerate(PROBLEMS):
        qid = f'practice-{ch}-{next_id + i}'
        q = {
            'id': qid,
            'subject': '감정평가실무',
            'chapter': ch,
            'source': 'practice-set',
            'subchapter': p['subchapter'],
            'difficulty': p['difficulty'],
            'points': p['points'],
            'topic': p['topic'],
            'body': p['body'],
            'modelAnswer': p['modelAnswer'],
            'modelAnswerSource': p['modelAnswerSource'],
            'answerFormat': p['answerFormat'],
            'keyPoints': p['keyPoints'],
        }
        data['questions'].append(q)
        added.append((qid, len(p['body']), len(p['modelAnswer']), p['points']))

    data['count'] = len(data['questions'])
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')

    print(f"3 표준 (기출 수준) +{len(added)}개 → 전체 {data['count']}")
    for qid, blen, alen, pts in added:
        print(f'  {qid}: 본문 {blen}자, 답안 {alen}자, {pts}점')


if __name__ == '__main__':
    main()
