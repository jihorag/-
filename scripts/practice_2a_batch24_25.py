    for prob in PROBLEMS:
        if prob['id'] in existing_ids:
            for i, q in enumerate(d['questions']):
                if q['id'] == prob['id']:
                    d['questions'][i] = prob
                    break
        else:
            d['questions'].append(prob)
            added += 1
    d['count'] = len(d['questions'])
    p.write_text(json.dumps(d, ensure_ascii=False), encoding='utf-8')
    print(f'2a Batch 24+25: +{added}개 → 전체 {len(d["questions"])}문제')


