def get_next_id(data, ch):
    next_id = max(
        (int(m.group(1)) for q in data['questions']
         for m in [re.match(rf'practice-{ch}-(\d+)', q['id'])] if m),
        default=0
    ) + 1
    return next_id


def add_problems(ch, problems):
    path = DATA / f'{ch}.json'
    data = json.loads(path.read_text(encoding='utf-8'))
    next_id = get_next_id(data, ch)
    added = []
    for i, p in enumerate(problems):
        qid = f'practice-{ch}-{next_id + i}'
        body = p['body']
        if len(body) < 30:
            body = '감정평가실무에서 ' + body
        q = {'id': qid, 'subject': '감정평가실무', 'chapter': ch,
             'source': 'practice-set', **p, 'body': body}
        data['questions'].append(q)
        added.append((qid, len(body), len(p['modelAnswer'])))
    data['count'] = len(data['questions'])
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    return added, data['count']


def main():
    all_added = []
    for ch, probs in [('4', CHAPTER_4), ('5', CHAPTER_5)]:
        a, c = add_problems(ch, probs)
        all_added.extend(a)
        print(f'단원 {ch} 입문 +{len(a)} → 총 {c}')

    m_path = DATA / 'manifest.json'
    m = json.loads(m_path.read_text())
    for c in m['chapters']:
        dd = json.loads((DATA / f'{c["id"]}.json').read_text())
        c['count'] = len(dd['questions'])
        c['withAnswer'] = sum(1 for q in dd['questions'] if q.get('modelAnswer'))
    m['total'] = sum(c['count'] for c in m['chapters'])
    m['built_at'] = datetime.now(timezone.utc).isoformat()
    m_path.write_text(json.dumps(m, ensure_ascii=False, indent=2))

    short_body = sum(1 for _, b, _ in all_added if b < 30)
    short_ans = sum(1 for _, _, a in all_added if a < 150)
    print(f'manifest total: {m["total"]}')
    print(f'본문<30: {short_body}, 답안<150: {short_ans}')


if __name__ == '__main__':
    main()
