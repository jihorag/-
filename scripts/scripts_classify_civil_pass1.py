def match(rules, concept):
    for kws, target in rules:
        if not kws:
            return target  # default
        for kw in kws:
            if kw in concept:
                return target
    return None

def main():
    data = json.load(open(PATH, encoding="utf-8"))
    n_total=n_assigned=n_residual=0
    resid_by_sec={}
    for q in data:
        if q.get("exam")=="[연습문제]": continue
        iv=q.get("indexing_v4") or {}
        mt=iv.get("mapped_taxonomy") or {}
        if mt.get("subject")!="민법": continue
        n_total+=1
        chapter=mt.get("chapter","") or ""
        section=mt.get("section","") or ""
        concept=((q.get("tags") or {}).get("concept") or "")
        # 절 없는 장 → 절 지정
        if chapter in SECTIONLESS:
            tgt=match(SECTIONLESS_RULES[chapter], concept)
            mt["section"]=tgt; mt["item"]=""
            n_assigned+=1; continue
        # 절 있는 장 → 관 지정
        rules=None
        if section=="제1절 총설" and "권리의 변동" in chapter:
            rules=S["제1절 총설"]  # placeholder; set real below
