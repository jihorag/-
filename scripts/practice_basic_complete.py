def make_problems(ch, topics, start):
    res = []
    for i, (sub, topic, body, points) in enumerate(topics):
        if isinstance(points, str): points = [points]
        res.append(basic(ch, start+i, sub, topic, f'[자료] {body}. 결과?', points))
    return res


def apply_batch(ch, problems):
    path = DATA_DIR / f'{ch}.json'
    data = json.loads(path.read_text(encoding='utf-8'))
    existing_ids = {q['id'] for q in data['questions']}
    new = [p for p in problems if p['id'] not in existing_ids]
    data['questions'].extend(new)
    data['count'] = len(data['questions'])
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f"{ch} 기초 +{len(new)}개 → 전체 {data['count']}")


def main():
    apply_batch('3', make_problems('3', TOPICS_3, 901))
    apply_batch('4', make_problems('4', TOPICS_4, 901))
    apply_batch('5', make_problems('5', TOPICS_5, 901))
    apply_batch('6b', make_problems('6b', TOPICS_6b, 901))
    apply_batch('7', make_problems('7', TOPICS_7, 801))
    apply_batch('8a', make_problems('8a', TOPICS_8a, 801))
    apply_batch('8b', make_problems('8b', TOPICS_8b, 801))


if __name__ == '__main__':
    main()
