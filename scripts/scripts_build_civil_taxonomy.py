def main():
    tax = json.load(open(PATH, encoding="utf-8"))
    civ = tax["민법"]["subjects"]
    total_items = 0
    total_secs = 0
    for sub, chapters in civ.items():
        design_sub = DESIGN[sub]
        for ch in chapters:
            d = design_sub[ch["name"]]
            if "__sections__" in d:
                # 절 없는 장 -> 학습 단위를 절로 추가 (items 비움)
                ch["sections"] = [{"name": s, "items": []} for s in d["__sections__"]]
                total_secs += len(ch["sections"])
            else:
                # 절 있는 장 -> 기존 절 이름 보존하며 items 채움
                existing = {s["name"] for s in ch.get("sections", [])}
                assert set(d.keys()) == existing, f"절 불일치 {ch['name']}: {set(d.keys())^existing}"
                for sec in ch["sections"]:
                    items = d[sec["name"]]
                    sec["items"] = [{"name": it} for it in items]
                    total_items += len(items)
    json.dump(tax, open(PATH, "w", encoding="utf-8"), ensure_ascii=False)
    print(f"taxonomy_v4.json 갱신 완료 — 추가 관(款) {total_items}개, 신규 절 {total_secs}개")

if __name__ == "__main__":
    main()
