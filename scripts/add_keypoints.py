def main():
    practice_dir = Path('viewer/public/data/essay/practice')
    for chapter_file in practice_dir.glob('*-generated.json'):
        data = json.loads(chapter_file.read_text(encoding='utf-8'))
        changed = False
        for q in data['questions']:
            qid = q['id']
            if qid in KEYPOINTS:
                q['keyPoints'] = KEYPOINTS[qid]
                changed = True
        if changed:
            chapter_file.write_text(json.dumps(data, ensure_ascii=False), encoding='utf-8')
            print(f'updated {chapter_file.name} — {sum(1 for q in data["questions"] if q.get("keyPoints"))}/{len(data["questions"])} questions tagged')


if __name__ == '__main__':
    main()
