def main():
    p = DATA_DIR / '3.json'
    d = json.loads(p.read_text(encoding='utf-8'))

    updated = 0
    for q in d['questions']:
        if q['id'] in ANSWERS:
            ans = ANSWERS[q['id']]
            q['modelAnswer'] = ans['modelAnswer']
            q['modelAnswerSource'] = ans['modelAnswerSource']
            q['keyPoints'] = ans['keyPoints']
            q.pop('answerMatchingWarning', None)
            updated += 1

    matched = sum(1 for q in d['questions'] if q.get('modelAnswer'))
    d['withAnswer'] = matched
    d['matchedAnswer'] = matched
    p.write_text(json.dumps(d, ensure_ascii=False), encoding='utf-8')
    print(f'단원 3: +{updated}개 → {matched}/{len(d["questions"])}')

    mpath = DATA_DIR / 'manifest.json'
    m = json.loads(mpath.read_text(encoding='utf-8'))
    for c in m['chapters']:
        if c['id'] == '3':
            c['withAnswer'] = matched
            c['matchedAnswer'] = matched
    m['classified'] = sum(c.get('matchedAnswer', 0) for c in m['chapters'])
    mpath.write_text(json.dumps(m, ensure_ascii=False), encoding='utf-8')

    if matched == len(d['questions']):
        print('★ 단원 3 완성!')


if __name__ == '__main__':
    main()
