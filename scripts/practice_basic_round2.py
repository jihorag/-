def make_problems(ch, topics, start_num):
    problems = []
    for i, (sub, topic, body, points) in enumerate(topics):
        if isinstance(points, str):
            points = [points]
        problems.append({
            'id': f'practice-{ch}-{start_num+i:03d}',
            'subject': '감정평가실무', 'chapter': ch,
            'source': 'practice-set', 'difficulty': 2, 'points': 10,
            'subchapter': sub, 'topic': topic,
            'body': f'[자료] {body}. 결과?',
            'modelAnswer': '## 핵심 정리\n\n- ' + '\n- '.join(points),
            'modelAnswerSource': 'ai-direct-essay',
            'answerFormat': 'essay-narrative',
            'keyPoints': points,
        })
    return problems


def apply_batch(ch, problems):
    path = DATA_DIR / f'{ch}.json'
    data = json.loads(path.read_text(encoding='utf-8'))
    existing_ids = {q['id'] for q in data['questions']}
    new = [p for p in problems if p['id'] not in existing_ids]
    data['questions'].extend(new)
    data['count'] = len(data['questions'])
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f"{ch} 기초 +{len(new)}개 → 전체 {data['count']}")


