def apply_answers(cid, answers_dict):
    p = DATA_DIR / f'{cid}.json'
    d = json.loads(p.read_text(encoding='utf-8'))
    updated = 0
    for q in d['questions']:
        if q['id'] in answers_dict:
            ans = answers_dict[q['id']]
            q['modelAnswer'] = ans['modelAnswer']
            q['modelAnswerSource'] = ans['modelAnswerSource']
            q['keyPoints'] = ans['keyPoints']
            q.pop('answerMatchingWarning', None)
            updated += 1
    matched = sum(1 for q in d['questions'] if q.get('modelAnswer'))
    d['withAnswer'] = matched
    d['matchedAnswer'] = matched
    p.write_text(json.dumps(d, ensure_ascii=False), encoding='utf-8')
    return updated, matched, len(d['questions'])


