    mf = DATA / 'manifest.json'
    m = json.loads(mf.read_text(encoding='utf-8'))
    official_2a = json.loads((DATA / f'{CH}.json').read_text(encoding='utf-8')).get('count', 0)
    for ch in m.get('chapters', []):
        if ch.get('id') == CH:
            ch['generatedCount'] = len(PROBLEMS)
            ch['count'] = official_2a + len(PROBLEMS)
    m['total'] = sum(ch.get('count', 0) for ch in m.get('chapters', []))
    mf.write_text(json.dumps(m, ensure_ascii=False, indent=1), encoding='utf-8')
