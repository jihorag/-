def main():
    path = Path('viewer/public/data/exams/08.json')
    data = json.loads(path.read_text(encoding='utf-8'))
    qs = data if isinstance(data, list) else data.get('questions', [])

    fixed = 0
    for q in qs:
        qid = q.get('id')
        if qid in FIXES:
            fix = FIXES[qid]
            if q.get('question') == fix['old']:
                q['question'] = fix['new']
                fixed += 1
                print(f'  ✓ {qid}')
            else:
                print(f'  ✗ {qid}: 본문 불일치')

    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'\n{fixed}/{len(FIXES)} 수정 완료')


if __name__ == '__main__':
    main()
