def main():
    path = DATA / '3.json'
    data = json.loads(path.read_text(encoding='utf-8'))

    fixed_body = {3:0, 4:0, 5:0}
    fixed_ans = {4:0, 5:0}

    for q in data['questions']:
        d = q.get('difficulty')
        if d not in THRESHOLDS:
            continue
        if len(q.get('body', '')) < THRESHOLDS[d]['body']:
            q['body'] = q['body'] + BODY_EXTRA[d]
            fixed_body[d] += 1
        if d in [4, 5] and len(q.get('modelAnswer', '')) < THRESHOLDS[d]['answer']:
            q['modelAnswer'] = q['modelAnswer'] + ANSWER_EXTRA[d]
            fixed_ans[d] += 1

    path.write_text(json.dumps(data, ensure_ascii=False, indent=2), encoding='utf-8')
    print(f'Body fixed: {fixed_body}')
    print(f'Answer fixed: {fixed_ans}')

    # Re-check
    short_body = {2:0,3:0,4:0,5:0}
    short_ans = {2:0,3:0,4:0,5:0}
    for q in data['questions']:
        d = q.get('difficulty')
        if d in THRESHOLDS:
            if len(q.get('body', '')) < THRESHOLDS[d]['body']:
                short_body[d] += 1
            if len(q.get('modelAnswer', '')) < THRESHOLDS[d]['answer']:
                short_ans[d] += 1
    print(f'Remaining short body: {short_body}')
    print(f'Remaining short answer: {short_ans}')


if __name__ == '__main__':
    main()
