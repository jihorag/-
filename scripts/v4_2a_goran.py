def make_goran_problem(topic, scenario, materials, scenario_decision, answer_body, keys):
    body_parts = [scenario]
    body_parts.extend(materials)
    body_parts.append(scenario_decision)
    body = '\n\n'.join(body_parts)
    if len(body) < 1500:
        body = PREFIX + body
    return body, answer_body, keys


def std_goran_answer(intro, sections, conclusion):
    parts = [f'Ⅰ. 평가개요\n{intro}']
    for i, s in enumerate(sections, 1):
        parts.append(f'Ⅱ. 본건 평가 - {i}\n{s}')
    parts.append(f'Ⅲ. 가격결정 의견\n{conclusion}')
    return '\n\n'.join(parts)


