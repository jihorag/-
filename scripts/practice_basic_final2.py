import json
import re
from pathlib import Path

DATA_DIR = Path('viewer/public/data/essay/practice')


def basic(ch, num, sub, topic, body, points):
    return {
        'id': f'practice-{ch}-{num:03d}',
        'subject': '감정평가실무', 'chapter': ch,
        'source': 'practice-set', 'difficulty': 2, 'points': 10,
        'subchapter': sub, 'topic': topic,
        'body': body,
        'modelAnswer': f"## 핵심 정리\n\n- " + '\n- '.join(points),
        'modelAnswerSource': 'ai-direct-essay',
        'answerFormat': 'essay-narrative',
        'keyPoints': points,
    }


def get_next_id(ch):
    d = json.loads((DATA_DIR / f'{ch}.json').read_text(encoding='utf-8'))
    nums = []
    for q in d['questions']:
        m = re.match(rf'practice-{ch}-(\d+)', q['id'])
        if m: nums.append(int(m.group(1)))
    return (max(nums) if nums else 0) + 1


