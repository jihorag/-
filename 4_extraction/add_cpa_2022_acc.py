def extract_answers_cpa(pdf_path):
    doc = fitz.open(pdf_path)
    text = ""
    for page in doc:
        text += page.get_text()
    doc.close()
    
    ans_map = {}
    lines = [l.strip() for l in text.split("\n") if l.strip()]
    
    found_acc = False
    for i, line in enumerate(lines):
        if "회계학" in line and "3교시" in line:
            found_acc = True
            j = i + 1
            while j < len(lines):
                parts = lines[j].split()
                # Extract pairs of Num Ans
                for k in range(0, len(parts)-1, 2):
                    try:
                        num = int(parts[k])
                        ans = parts[k+1]
                        if 1 <= num <= 50:
                            ans_map[num] = ans
                    except: pass
                if j > i + 20: break # Safety exit
                j += 1
            break
    return ans_map

def main():
    # 1. Parse choices
    choices = {}
    pattern = r"## (\d+)번 문항\n(.*?)(?=\n##|$)"
