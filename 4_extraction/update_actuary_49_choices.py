    def parse_choices(text):
        parsed = {}
        # Pattern to match "N번: ①... ②... ③... ④..."
        matches = re.findall(r"\*\*(\d+)번:\*\*\s*(.*?)(?=\*\*|$)", text, re.DOTALL)
        for num_str, content in matches:
            num = int(num_str)
            # Split by circle numbers
            opts = re.split(r"[①②③④⑤]", content)
            opts = [o.strip() for o in opts if o.strip()]
            parsed[num] = opts
        return parsed

